function toUnit(seed: UnitSeed): ContextUnit {
  const included =
    seed.classification !== "omitted" && seed.classification !== "stale";
  return {
    id: seed.id,
    ref: seed.ref,
    category: seed.category,
    label: seed.label,
    text: seed.text,
    tokens: seed.tokens,
    compiledTokens: included ? (seed.compiled ?? seed.tokens) : 0,
    classification: seed.classification,
    risk: seed.risk,
    authority: seed.authority,
    trust: seed.trust,
    relevance: seed.relevance,
    included,
    reason: seed.reason,
    dependencies: seed.deps ?? [],
    recovered: seed.recovered,
    supersededBy: seed.supersededBy,
    supersedes: seed.supersedes,
  };
}

export const DEMO_CONTEXT_UNITS: ContextUnit[] = SEEDS.map(toUnit);

export const DEMO_UNIT_INDEX: ReadonlyMap<string, ContextUnit> = new Map(
  DEMO_CONTEXT_UNITS.map((unit) => [unit.id, unit]),
);

export function getDemoUnit(id: string): ContextUnit | undefined {
  return DEMO_UNIT_INDEX.get(id);
}

/** Units restored by auto-recovery after the first verification pass failed. */
export const DEMO_RECOVERED_UNIT_IDS: string[] = DEMO_CONTEXT_UNITS.filter(
  (u) => u.recovered,
).map((u) => u.id);

